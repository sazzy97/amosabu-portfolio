"use client";

import { motion, useScroll, useSpring } from "framer-motion";

export default function ScrollProgress() {
  const { scrollYProgress } = useScroll();
  const scaleX = useSpring(scrollYProgress, {
    stiffness: 220,
    damping: 32,
    restDelta: 0.001,
  });

  return (
    <motion.div
      className="fixed top-0 left-0 right-0 h-[2.5px] bg-[#ff5900] origin-left z-50 pointer-events-none shadow-[0_0_10px_rgba(255,89,0,0.7)]"
      style={{ scaleX }}
    />
  );
}
